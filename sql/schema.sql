-- PostgreSQL 16 schema for the study material recommender (recommend_db)
-- Converted from the legacy MySQL dump; see scripts/migrate_mysql_to_postgres.py.

SET client_encoding = 'UTF8';

DROP TABLE IF EXISTS
    ai_conversations,
    material_comments,
    material_likes,
    recommendation_feedback,
    recommendations,
    user_behaviors,
    user_favorites,
    user_preferences,
    user_ratings,
    materials,
    categories,
    users;

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(50)  NOT NULL,
    password       VARCHAR(255) NOT NULL,
    email          VARCHAR(100),
    phone          VARCHAR(20),
    role           VARCHAR(10)  NOT NULL DEFAULT 'USER'
                   CHECK (role IN ('USER', 'ADMIN')),
    target_school  VARCHAR(100),
    major          VARCHAR(100),
    study_phase    VARCHAR(20)  DEFAULT 'PREPARATION'
                   CHECK (study_phase IN ('PREPARATION', 'INITIAL', 'INTENSIVE', 'REVIEW')),
    avatar_url     VARCHAR(500),
    enabled        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_users_username_lower ON users (lower(username));
CREATE UNIQUE INDEX uk_users_email_lower ON users (lower(email)) WHERE email IS NOT NULL;

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    parent_id   BIGINT,
    description VARCHAR(255),
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_category_parent FOREIGN KEY (parent_id)
        REFERENCES categories (id) ON DELETE SET NULL
        DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX idx_category_parent ON categories (parent_id);

CREATE TABLE materials (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(200) NOT NULL,
    description    TEXT,
    category_id    BIGINT,
    tags           VARCHAR(500),
    hdfs_path      VARCHAR(500),
    file_name      VARCHAR(255),
    file_size      BIGINT,
    author         VARCHAR(100),
    rating_avg     NUMERIC(3, 2) DEFAULT 0.00,
    rating_count   INTEGER       DEFAULT 0,
    view_count     INTEGER       DEFAULT 0,
    download_count INTEGER       DEFAULT 0,
    status         VARCHAR(10)   NOT NULL DEFAULT 'PENDING'
                   CHECK (status IN ('ACTIVE', 'PENDING', 'DELETED')),
    uploader_id    BIGINT,
    created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_material_category FOREIGN KEY (category_id)
        REFERENCES categories (id) ON DELETE SET NULL
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_material_uploader FOREIGN KEY (uploader_id)
        REFERENCES users (id) ON DELETE SET NULL
        DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX idx_material_category ON materials (category_id);
CREATE INDEX idx_material_uploader ON materials (uploader_id);

CREATE TABLE ai_conversations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL,
    question    TEXT        NOT NULL,
    answer      TEXT,
    type        VARCHAR(10) NOT NULL DEFAULT 'CHAT'
                CHECK (type IN ('CHAT', 'SUMMARY', 'SUGGESTION', 'SEARCH')),
    material_id BIGINT,
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_conv_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX idx_conversation_user ON ai_conversations (user_id);

CREATE TABLE material_comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    material_id BIGINT NOT NULL,
    content     TEXT   NOT NULL,
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_material_comment_material FOREIGN KEY (material_id)
        REFERENCES materials (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_material_comment_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX idx_material_comment_material ON material_comments (material_id, created_at DESC);
CREATE INDEX idx_material_comment_user ON material_comments (user_id);

CREATE TABLE material_likes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    material_id BIGINT NOT NULL,
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_material_like_user_material UNIQUE (user_id, material_id),
    CONSTRAINT fk_material_like_material FOREIGN KEY (material_id)
        REFERENCES materials (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_material_like_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX idx_material_like_material ON material_likes (material_id);

CREATE TABLE recommendation_feedback (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL,
    material_id BIGINT      NOT NULL,
    feedback    VARCHAR(10) NOT NULL
                CHECK (feedback IN ('LIKE', 'DISLIKE')),
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_feedback_user_material UNIQUE (user_id, material_id),
    CONSTRAINT fk_feedback_material FOREIGN KEY (material_id)
        REFERENCES materials (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_feedback_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX idx_feedback_material ON recommendation_feedback (material_id);

CREATE TABLE recommendations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL,
    material_id BIGINT        NOT NULL,
    score       NUMERIC(10, 6) NOT NULL DEFAULT 0.000000,
    algorithm   VARCHAR(10)   NOT NULL DEFAULT 'HYBRID'
                CHECK (algorithm IN ('USERCF', 'ITEMCF', 'TFIDF', 'HYBRID')),
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_rec_user_material UNIQUE (user_id, material_id),
    CONSTRAINT fk_rec_material FOREIGN KEY (material_id)
        REFERENCES materials (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_rec_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX idx_rec_user_score ON recommendations (user_id, score DESC);
CREATE INDEX idx_rec_material ON recommendations (material_id);

CREATE TABLE user_behaviors (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL,
    material_id BIGINT      NOT NULL,
    action      VARCHAR(10) NOT NULL
                CHECK (action IN ('VIEW', 'LIKE', 'DISLIKE', 'COLLECT', 'RATE', 'DOWNLOAD', 'COMMENT')),
    score       NUMERIC(4, 2),
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_behavior_material FOREIGN KEY (material_id)
        REFERENCES materials (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_behavior_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX idx_user_behavior ON user_behaviors (user_id, material_id);
CREATE INDEX idx_action_time ON user_behaviors (action, created_at);
CREATE INDEX idx_behavior_material ON user_behaviors (material_id);

CREATE TABLE user_favorites (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    material_id BIGINT NOT NULL,
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_user_favorite UNIQUE (user_id, material_id),
    CONSTRAINT fk_favorite_material FOREIGN KEY (material_id)
        REFERENCES materials (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_favorite_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX idx_favorite_material ON user_favorites (material_id);

CREATE TABLE user_preferences (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT NOT NULL UNIQUE,
    preferred_categories VARCHAR(500),
    preferred_tags       VARCHAR(500),
    excluded_tags        VARCHAR(500),
    top_n                INTEGER NOT NULL DEFAULT 10,
    auto_refresh         BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pref_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE user_ratings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT   NOT NULL,
    material_id BIGINT   NOT NULL,
    rating      SMALLINT NOT NULL,
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_user_material UNIQUE (user_id, material_id),
    CONSTRAINT fk_rating_material FOREIGN KEY (material_id)
        REFERENCES materials (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_rating_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
        DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX idx_rating_material ON user_ratings (material_id);
